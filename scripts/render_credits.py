#!/usr/bin/env python3
"""Render Super Artemis credits from app/src/main/res/raw/credits.json.

The JSON file is the single source of truth. The app reads it for Settings > About > Credits, and this script renders the same data into README.md and into release notes.

Usage:
  python scripts/render_credits.py --write           update the README block between the credits markers
  python scripts/render_credits.py --check           exit 1 if the README block is missing or stale (used by CI)
  python scripts/render_credits.py --release-notes   print the Thanks section for a GitHub release body
"""
import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CREDITS = ROOT / "app" / "src" / "main" / "res" / "raw" / "credits.json"
README = ROOT / "README.md"
START = "<!-- credits:start (generated by scripts/render_credits.py, edit credits.json instead) -->"
END = "<!-- credits:end -->"

# Contributions that shipped code or designs come first, community requests after
CONTRIBUTOR_ROLES = ("base", "code", "design", "prior-art", "library", "assets", "idea")
COMMUNITY_ROLES = ("request", "report")


def load():
    data = json.loads(CREDITS.read_text(encoding="utf-8"))
    if data.get("schemaVersion") != 1:
        raise SystemExit("Unsupported credits.json schemaVersion")
    for entry in data["entries"]:
        if entry["role"] not in data["roles"]:
            raise SystemExit("Unknown role '%s' in entry '%s'" % (entry["role"], entry["feature"]))
    return data


def person_md(person):
    return "[@%s](https://github.com/%s)" % (person["handle"], person["handle"])


def links_md(entry):
    return ", ".join("[%s](%s)" % (link["label"], link["url"]) for link in entry["links"])


def readme_block(data):
    lines = [START, "", "| Feature | Credit | Contribution | Links |", "| :--- | :--- | :--- | :--- |"]
    for role in CONTRIBUTOR_ROLES + COMMUNITY_ROLES:
        for entry in (e for e in data["entries"] if e["role"] == role):
            people = ", ".join(person_md(p) for p in entry["people"]) or "Google"
            lines.append("| %s | %s | %s | %s |" % (entry["feature"], people, data["roles"][role], links_md(entry)))
    lines += ["", END]
    return "\n".join(lines)


def release_notes(data):
    def handles(roles):
        seen = []
        for entry in data["entries"]:
            if entry["role"] in roles:
                for person in entry["people"]:
                    if person["handle"] not in seen:
                        seen.append(person["handle"])
        return " ".join("@" + h for h in seen)

    out = ["### Thanks", ""]
    out.append("Super Artemis builds on code and designs by " + handles(CONTRIBUTOR_ROLES) + ".")
    community = handles(COMMUNITY_ROLES)
    if community:
        out.append("")
        out.append("Shaped by requests and reports from " + community + ".")
    out.append("")
    out.append("Full credits with links are in the README and in Settings > About > Credits.")
    return "\n".join(out)


def current_readme_block(text):
    start = text.find(START)
    end = text.find(END)
    if start == -1 or end == -1 or end < start:
        return None
    return text[start:end + len(END)]


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--release-notes", action="store_true")
    args = parser.parse_args()

    data = load()
    if args.release_notes:
        print(release_notes(data))
        return 0

    text = README.read_text(encoding="utf-8")
    existing = current_readme_block(text)
    expected = readme_block(data)
    if existing is None:
        print("README.md has no credits markers. Add the start and end markers where the table belongs.", file=sys.stderr)
        return 1
    if args.check:
        if existing != expected:
            print("README.md credits are stale. Run: python scripts/render_credits.py --write", file=sys.stderr)
            return 1
        print("README.md credits are up to date.")
        return 0
    README.write_text(text.replace(existing, expected), encoding="utf-8", newline="\n")
    print("README.md credits updated.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
